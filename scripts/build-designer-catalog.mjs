import fs from 'node:fs';
import vm from 'node:vm';
const context=vm.createContext({});
for(const name of ['neolith-data.js','quartz-data.js'])vm.runInContext(fs.readFileSync(new URL('../dist/'+name,import.meta.url),'utf8'),context);
const list=vm.runInContext('[...neolithMaterials,...quartzMaterials]',context);
const catalog=Object.fromEntries(list.map(m=>[m.type+':'+m.id,{name:m.name,label:m.label,image:m.image}]));
if(Object.keys(catalog).length!==103)throw Error('Expected 103 unique materials');
fs.writeFileSync(new URL('../server/designer/catalog.mjs',import.meta.url),'// Generated by scripts/build-designer-catalog.mjs; do not edit.\nexport default '+JSON.stringify(catalog,null,2)+';\n');
console.log('Designer server allowlist: 103 materials');
