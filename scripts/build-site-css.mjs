import {readFile, writeFile} from 'node:fs/promises';
const root = new URL('../', import.meta.url);

/* The approved home page styles its header, menu, buttons and footer under `.architectural`, together with resets
   that only suit the home page. Every other page uses the same chrome under `.site`: the chrome rules are copied
   from architectural.css here, so that file stays the one place where the header and footer are designed. */
const CHROME = /atelier-(header|nav|phone|menu|mobile-nav|action|footer|brand)|skip-link|js-ready/;

function blocks(css) {
  const out = []; let depth = 0, start = 0, head = '';
  for (let i = 0; i < css.length; i++) {
    if (css[i] === '{') { if (depth === 0) { head = css.slice(start, i).trim(); start = i + 1; } depth++; }
    else if (css[i] === '}') { depth--; if (depth === 0) { out.push({head, body: css.slice(start, i)}); start = i + 1; } }
  }
  return out;
}
function mirrorRules(css) {
  return blocks(css).map(({head, body}) => {
    if (head.startsWith('@media')) { const inner = mirrorRules(body); return inner ? `${head}{${inner}}` : ''; }
    if (head.startsWith('@') || head.startsWith('/*')) return '';
    const selectors = head.replace(/\/\*[\s\S]*?\*\//g, '').split(',').map(s => s.trim()).filter(s => s.includes('.architectural') && CHROME.test(s));
    return selectors.length ? `${selectors.map(s => s.replaceAll('.architectural', '.site')).join(',')}{${body}}` : '';
  }).filter(Boolean).join('\n');
}

export async function buildSiteCss() {
  const approved = await readFile(new URL('dist/architectural.css', root), 'utf8');
  const own = await readFile(new URL('src/site.css', root), 'utf8');
  const css = `/* Generated by scripts/build-site-css.mjs — edit src/site.css (pages) or dist/architectural.css (header and footer). */\n${mirrorRules(approved)}\n${own}`;
  await writeFile(new URL('dist/site.css', root), css);
  return css;
}
